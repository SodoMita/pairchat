import type { NextRequest } from "next/server";

export async function readLimitedJson(
  request: NextRequest,
  maxBytes = 12_000,
): Promise<Record<string, unknown> | null> {
  const declaredLength = Number(request.headers.get("content-length") ?? "0");
  if (declaredLength > maxBytes) return null;

  const reader = request.body?.getReader();
  if (!reader) return null;

  const chunks: Uint8Array[] = [];
  let totalBytes = 0;
  try {
    while (true) {
      const { value, done } = await reader.read();
      if (done) break;
      totalBytes += value.byteLength;
      if (totalBytes > maxBytes) {
        await reader.cancel();
        return null;
      }
      chunks.push(value);
    }

    const bytes = new Uint8Array(totalBytes);
    let offset = 0;
    for (const chunk of chunks) {
      bytes.set(chunk, offset);
      offset += chunk.byteLength;
    }

    const parsed: unknown = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
    return parsed !== null && typeof parsed === "object" && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : null;
  } catch {
    await reader.cancel().catch(() => {});
    return null;
  }
}

export function bearerCredential(request: NextRequest) {
  const authorization = request.headers.get("authorization");
  const match = authorization?.match(/^Bearer ([A-Za-z0-9_-]{26,100})$/u);
  return match?.[1] ?? null;
}

export function abuseSessionCredential(request: NextRequest) {
  return request.headers.get("x-luma-abuse-session");
}

export function requestClientAddress(request: NextRequest) {
  // Do not trust a user-controlled X-Forwarded-For chain. Production ingress
  // should overwrite one of these single-address headers before the app sees it.
  return (
    request.headers.get("x-real-ip") ||
    request.headers.get("cf-connecting-ip") ||
    "unknown"
  );
}

export function isTrustedJsonMutation(request: NextRequest) {
  const contentType = request.headers.get("content-type")?.toLowerCase() ?? "";
  if (!contentType.startsWith("application/json")) return false;

  const fetchSite = request.headers.get("sec-fetch-site")?.toLowerCase();
  // Fetch Metadata is generated by the browser and cannot be spoofed by web content.
  if (fetchSite === "same-origin") return true;
  if (fetchSite === "cross-site" || fetchSite === "none") return false;

  const origin = request.headers.get("origin");
  if (!origin) return true;
  try {
    const originUrl = new URL(origin);
    const candidateHosts = [
      ...(request.headers.get("x-forwarded-host")?.split(",") ?? []),
      request.headers.get("host") ?? "",
      request.nextUrl.host,
    ].map((host) => host.trim().toLowerCase());
    return candidateHosts.includes(originUrl.host.toLowerCase());
  } catch {
    return false;
  }
}
